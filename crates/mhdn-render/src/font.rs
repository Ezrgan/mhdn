use crate::draw::Quad;

pub const GLYPH_W: f32 = 5.0;
pub const GLYPH_H: f32 = 7.0;
pub const ADVANCE: f32 = 6.0;

pub fn text_quads(text: &str, x: f32, y: f32, scale: f32, color: [f32; 4]) -> Vec<Quad> {
    let mut quads = Vec::new();
    let mut cursor = x;
    for ch in text.chars() {
        for (row, bits) in glyph(ch).into_iter().enumerate() {
            for col in 0..5 {
                if bits & (1 << (4 - col)) != 0 {
                    quads.push(Quad {
                        x: cursor + col as f32 * scale,
                        y: y + row as f32 * scale,
                        w: scale,
                        h: scale,
                        color,
                    });
                }
            }
        }
        cursor += ADVANCE * scale;
    }
    quads
}

